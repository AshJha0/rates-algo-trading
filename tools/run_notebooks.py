"""Execute the research notebooks and render them as Markdown pages for the docs site.

Each notebook in research/notebooks/ is a thin wrapper over ratesresearch functions. This
script runs every notebook top to bottom with nbclient (a failing cell fails the script, so CI
catches a broken notebook), then writes research/notebooks/_build/<name>.md: code cells as
python blocks, Markdown output inline, SVG output inline, plain text output in a text block.
docs/site/hooks.py publishes those files as site pages; the _build directory is not committed.

Usage: python tools/run_notebooks.py [repo root]
"""

from __future__ import annotations

import sys
from pathlib import Path

import nbformat
from nbclient import NotebookClient


def render(nb: nbformat.NotebookNode) -> str:
    parts: list[str] = []
    for cell in nb.cells:
        if cell.cell_type == "markdown":
            parts.append(cell.source.strip() + "\n")
            continue
        parts.append("```python\n" + cell.source.strip() + "\n```\n")
        for out in cell.get("outputs", []):
            data = out.get("data", {})
            if "text/markdown" in data:
                parts.append(str(data["text/markdown"]).strip() + "\n")
            elif "image/svg+xml" in data:
                parts.append('<div class="nb-svg">\n' + str(data["image/svg+xml"]).strip() + "\n</div>\n")
            elif "text/plain" in data:
                parts.append("```text\n" + str(data["text/plain"]).strip() + "\n```\n")
            elif out.get("output_type") == "stream":
                parts.append("```text\n" + str(out.get("text", "")).strip() + "\n```\n")
    return "\n".join(parts)


def main(root: Path) -> int:
    src = root / "research" / "notebooks"
    build = src / "_build"
    build.mkdir(exist_ok=True)
    names = sorted(src.glob("*.ipynb"))
    for path in names:
        nb = nbformat.read(path, as_version=4)
        NotebookClient(nb, timeout=600, kernel_name="python3", resources={"metadata": {"path": str(src)}}).execute()
        page = (
            f"<!-- generated by tools/run_notebooks.py from research/notebooks/{path.name}; do not edit -->\n\n"
            + render(nb)
        )
        (build / f"{path.stem}.md").write_text(page, encoding="utf-8", newline="\n")
        print(f"executed {path.name}")
    print(f"notebooks: {len(names)} executed and rendered to {build.relative_to(root).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]))
