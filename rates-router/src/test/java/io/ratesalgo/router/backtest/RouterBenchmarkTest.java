package io.ratesalgo.router.backtest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.ratesalgo.router.RouterPresets;
import io.ratesalgo.router.sim.ImpactVenueSpec;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import org.junit.jupiter.api.Test;

/**
 * The router benchmark (docs/research/ROUTER_BENCHMARK.md). It asserts only what must hold
 * whatever the numbers: every parent of every strategy completes, no fill is outside its order's
 * limit, the router never prices past its 2-tick collar and never crosses itself, and its
 * risk-adjusted cost is not worse than baselines (a) to (c) by more than the scenario's
 * tolerance. Against (d) that declared check failed on the one run, and the test holds the
 * report to saying so. The measured numbers go to the report, written when {@code
 * -Drouter.benchmark.report=<path>} is set; {@code -Drouter.benchmark.commit=<hash>} names the
 * commit that fixed the scenario.
 */
class RouterBenchmarkTest {

  static final String COMMAND =
      "mvn -o -B -ntp -pl rates-router -am test -Dtest=RouterBenchmarkTest"
          + " -Dsurefire.failIfNoSpecifiedTests=false -Djacoco.skip=true"
          + " -Drouter.benchmark.report=../docs/research/ROUTER_BENCHMARK.md"
          + " -Drouter.benchmark.commit=<scenario commit>";

  @Test
  void routerAgainstRealBaselinesOnTheImpactMarket() throws IOException {
    final RouterBenchmarkScenario sc = RouterBenchmarkScenario.ust10yImpactV1();
    final RouterBenchmarkResult r = RouterBenchmark.run(sc, RouterBenchmark.strategies(sc));
    final String commit = System.getProperty("router.benchmark.commit", "(not given)");
    final String body = r.markdown(COMMAND, commit);
    System.out.print(body);
    final String path = System.getProperty("router.benchmark.report");
    if (path != null && !path.isBlank()) {
      // the report is LF like every file in the repository, whatever %n is here
      Files.writeString(
          Path.of(path), (intro(sc) + body).replace("\r\n", "\n"), StandardCharsets.UTF_8);
    }
    for (int s = 0; s < r.strategies(); s++) {
      assertEquals(1.0, r.fillRate(s), 1e-12, r.name(s) + " left parents unfilled");
      assertEquals(0, r.violations(s), r.name(s) + " filled outside an order limit");
    }
    assertTrue(r.maxTicksPastTouch(0) <= RouterPresets.ladder().aggressiveCollarTicks(),
        "router priced past its collar: " + r.maxTicksPastTouch(0));
    assertEquals(0, r.selfCrosses(0), "router crossed its own order");
    // The check declared before the run (router no worse than each real baseline by more than
    // the tolerance) held against (a), (b) and (c) and FAILED against (d), passive with a
    // deadline, by 0.40 ticks on the one run of 2026-11-23. The scenario was not changed to
    // alter that: (a) to (c) stay asserted, and (d) is asserted to be reported as failing, so
    // the report cannot silently change its answer.
    for (int s = 1; s <= 3; s++) {
      final double worse = r.riskAdjustedTicks(0) - r.riskAdjustedTicks(s);
      assertTrue(r.withinTolerance(s),
          String.format(Locale.ROOT, "router risk-adjusted cost %.3f ticks worse than %s",
              worse, r.name(s)));
    }
    assertTrue(
        !r.withinTolerance(4) && body.contains("(d) passive, deadline: router worse by")
            && body.contains("FAILS"),
        "the recorded result against (d) changed: rerun and update the report");
  }

  /** The report's fixed opening: what it is, what it is not, and the scenario. */
  static String intro(final RouterBenchmarkScenario sc) {
    final StringBuilder sb = new StringBuilder(4_096);
    sb.append("# Router benchmark\n\n");
    sb.append("Generated by `RouterBenchmarkTest`; do not edit by hand. This is a result of the router's own"
        + " synthetic simulator (`ImpactMarket`), not a market finding: it says how the router behaves"
        + " in a model whose every number is a declared assumption, against alternatives a desk would"
        + " actually use. It replaces the 2.94 bp row, which compared the router with orders fired"
        + " whole into thin touch depth (review section 5.1).\n\n");
    sb.append("## Scenario\n\n");
    sb.append("The router is given only what a desk would know: published fees, lot and tick, its"
        + " measured latency, a daily volume figure and a declared cancellation-rate prior of 0.2 per"
        + " second (`ImpactConfig.declaredVenues`). Queue cancellation and order arrival rates are"
        + " learned from trade prints and book decrements; the simulator's own rates are never passed"
        + " in. A fresh router each day: nothing it learns carries over.\n\n");
    sb.append("| venue | spread (ticks) | touch depth (lots) | per level | market orders /s/side | mean size |"
        + " cancel /lot/s | refill /s | latency (us) | taker | maker | rejects |\n");
    sb.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n");
    for (final ImpactVenueSpec v : sc.market().venues()) {
      sb.append(String.format(Locale.ROOT, "| %d | %d | %.0f | %.0f | %.1f | %.0f | %.2f | %.1f | %d | %.4f | %.4f | %.0f%% |%n",
          v.venueId(), v.spreadTicks(), v.topDepthLots(), v.depthStepLots(), v.marketOrdersPerSecond(),
          v.meanOrderLots(), v.cancelRatePerSecond(), v.refillPerSecond(), v.latencyNanos() / 1_000,
          v.takerFee(), v.makerFee(), v.rejectProbability() * 100));
    }
    sb.append(String.format(Locale.ROOT,
        "%nEfficient price: %.3f ticks per root second (0.5 price points a day); every lot anyone takes"
            + " moves it %.2f ticks for good, and the depth taken refills, so resilience is below 100%%."
            + " Steps of %d ms, %d levels a side. Parents: %d to %d lots of 1 million, random side, %d s apart,"
            + " urgency %.1f; the router's nominal schedule at that urgency is 5 slices over 60 s with 15 s"
            + " passive, which baselines (b) and (c) follow and (d) uses as its 75 s deadline.%n%n",
        sc.market().sigmaTicksPerSqrtSecond(), sc.market().permanentTicksPerLot(),
        sc.market().stepNanos() / 1_000_000, sc.market().levels(), sc.minLots(), sc.maxLots(),
        sc.gapNanos() / 1_000_000_000L, sc.urgency()));
    sb.append("Strategies: the router (ladder model, `RouterPresets.ladder()` with"
        + " `ExecutionModel.defaults()`); (a) the whole parent swept best all-in price first across"
        + " venues on arrival; (b) the router's time schedule swept on the single best venue (venue 1);"
        + " (c) TWAP across venues, each slice swept best price first; (d) resting at the best touch,"
        + " re-posted when the touch moves away, swept at the deadline; (e) the old single-shot and"
        + " even-split baselines with an 8-tick collar, labelled strawmen; and the touch-model router"
        + " (v1 preset) for reference. Sweeps read 10 levels and retry remainders after 0.5 s.\n\n");
    sb.append(String.format(Locale.ROOT,
        "Declared before the run: the router's risk-adjusted cost should be no worse than any of (a)"
            + " to (d) by more than %.2f ticks. The one run met that against (a), (b) and (c) and did not"
            + " against (d) (see the check at the end); the scenario was not changed. The test asserts"
            + " the check for (a) to (c), that the report records the failure against (d), that every"
            + " parent completes, that no fill is outside its order's limit, and that the router never"
            + " prices past its 2-tick collar or crosses itself.%n%n",
        sc.toleranceTicks()));
    sb.append("One run. The numbers are deterministic for the seed, so regenerating the file with the"
        + " command at the end repeats the same run. A first attempt stopped before producing any number"
        + " (a strawman baseline hung on a rejected order; fixed in 20484e2).\n\n");
    return sb.toString();
  }
}
