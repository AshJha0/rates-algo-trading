package io.ratesalgo.analytics.bond;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.ratesalgo.analytics.date.Dates;
import io.ratesalgo.analytics.golden.Golden;
import java.util.Map;
import net.jqwik.api.ForAll;
import net.jqwik.api.Property;
import net.jqwik.api.constraints.IntRange;
import org.junit.jupiter.api.Test;

/**
 * The dated date of a Treasury whose nominal date falls on a weekend (review 2026-11-23, A5).
 *
 * <p>Convention: the Treasury dates a note on its nominal date, the 15th or the last day of the
 * month, and issues it on the next business day; interest accrues from the dated date (31 CFR
 * 356.2, "dated date"), the first coupon is a full half-year coupon and the buyer pays the accrued
 * interest from the dated date to the issue date (31 CFR 356, Appendix B). The fixture's 2-year
 * and 5-year notes mature on 31 October and were issued on Monday 2026-11-02, so both are dated
 * Saturday 2026-10-31. Building them from the issue date instead gives a first coupon two days
 * short.
 */
class DatedDateTest {

  private static final BondPricer P = new BondPricer();
  private static final int DATED = Dates.of(2026, 10, 31);
  private static final int ISSUE = Dates.of(2026, 11, 2);
  private static final int FIRST_COUPON = Dates.of(2027, 4, 30);
  /** 31 October 2026 to 30 April 2027. */
  private static final int DAYS_IN_FIRST_PERIOD = 181;

  private static FixedRateBond twoYear(final int dated) {
    return new FixedRateBond("UST 3.375 2028-10-31", BondConvention.UST, 0.03375, dated,
        Dates.of(2028, 10, 31));
  }

  private static FixedRateBond fiveYear(final int dated) {
    return new FixedRateBond("UST 3.625 2031-10-31", BondConvention.UST, 0.03625, dated,
        Dates.of(2031, 10, 31));
  }

  @Test
  void weekendDatedTwoAndFiveYearPayAFullFirstCoupon() {
    // exact in binary up to one rounding: 100 * coupon / 2
    assertEquals(1.6875, twoYear(DATED).couponAmount(0), 1e-13);
    assertEquals(1.8125, fiveYear(DATED).couponAmount(0), 1e-13);
    assertEquals(FIRST_COUPON, twoYear(DATED).couponDate(0));
    assertEquals(4, twoYear(DATED).couponCount());
    assertEquals(10, fiveYear(DATED).couponCount());
  }

  @Test
  void accruedRunsFromTheDatedDateNotTheIssueDate() {
    // regular settlement of a trade on the issue date: Tuesday 3 November, three days of interest
    final int settle = twoYear(DATED).settlementDate(ISSUE);
    assertEquals(Dates.of(2026, 11, 3), settle);
    // actual/actual: half-year coupon times days accrued over days in the period; 1e-13 is a few
    // ulps of the product
    assertEquals(1.6875 * 3 / DAYS_IN_FIRST_PERIOD, P.accrued(twoYear(DATED), settle), 1e-13);
    assertEquals(1.8125 * 3 / DAYS_IN_FIRST_PERIOD, P.accrued(fiveYear(DATED), settle), 1e-13);
    // what the buyer pays at issue: two days
    assertEquals(1.6875 * 2 / DAYS_IN_FIRST_PERIOD, P.accrued(twoYear(DATED), ISSUE), 1e-13);
  }

  @Test
  void datingTheNoteOnItsIssueDateLosesTwoDaysOfTheFirstCoupon() {
    // the defect: 0.0187 per 100 on the 2-year, 186 dollars per million face
    final double shortfall = twoYear(DATED).couponAmount(0) - twoYear(ISSUE).couponAmount(0);
    assertEquals(1.6875 * 2 / DAYS_IN_FIRST_PERIOD, shortfall, 1e-13);
    assertEquals(0.0186, shortfall, 1e-4);
    assertEquals(0.0200, fiveYear(DATED).couponAmount(0) - fiveYear(ISSUE).couponAmount(0), 1e-4);
    // and one day of accrued instead of three at regular settlement
    final int settle = Dates.of(2026, 11, 3);
    assertEquals(1.6875 / DAYS_IN_FIRST_PERIOD, P.accrued(twoYear(ISSUE), settle), 1e-13);
  }

  @Test
  void thePublishedFirstCouponDateCatchesAWrongDatedDate() {
    final int maturity = Dates.of(2028, 10, 31);
    final FixedRateBond ok =
        new FixedRateBond("ok", BondConvention.UST, 0.03375, DATED, FIRST_COUPON, maturity);
    assertEquals(1.6875, ok.couponAmount(0), 1e-13);
    // dated on the issue date the first coupon still falls on 30 April, so the date alone cannot
    // tell; a dated date a period early does move it and is refused
    final IllegalArgumentException e = assertThrows(IllegalArgumentException.class,
        () -> new FixedRateBond("bad", BondConvention.UST, 0.03375, Dates.of(2026, 4, 30),
            FIRST_COUPON, maturity));
    assertTrue(e.getMessage().contains("2026-10-31") && e.getMessage().contains("2027-04-30"),
        e.getMessage());
  }

  /**
   * The same note in QuantLib (golden case UST-3.375-2028-10-31-DATED-SATURDAY, generated by
   * research/ratesresearch/goldens): accrued and the clean price at 3.40 percent agree to the
   * golden gate's 1e-10 per 100.
   */
  @Test
  void quantLibAgreesOnTheWeekendDatedTwoYear() {
    Map<String, Object> row = null;
    for (final Map<String, Object> r : Golden.list(Golden.load(), "bonds")) {
      if ("UST-3.375-2028-10-31-DATED-SATURDAY".equals(Golden.str(r, "id"))) {
        row = r;
      }
    }
    final FixedRateBond b = twoYear(Golden.date(row, "dated"));
    final int settle = b.settlementDate(Golden.date(row, "trade"));
    assertEquals(Golden.num(row, "accrued"), P.accrued(b, settle), 1e-10);
    assertEquals(1.6875 * 3 / DAYS_IN_FIRST_PERIOD, Golden.num(row, "accrued"), 1e-13);
    assertEquals(Golden.num(row, "clean"), P.cleanPrice(b, Golden.num(row, "yield"), settle), 1e-10);
  }

  /**
   * For any month-end or mid-month Treasury dated on its nominal date, however many days later it
   * is issued, the first coupon is the full half-year coupon.
   */
  @Property(tries = 200)
  void aNoteDatedOnItsNominalDateAlwaysHasAFullFirstCoupon(
      @ForAll @IntRange(min = 2020, max = 2040) final int year,
      @ForAll @IntRange(min = 1, max = 12) final int month,
      @ForAll final boolean monthEnd,
      @ForAll @IntRange(min = 2, max = 30) final int years,
      @ForAll @IntRange(min = 1, max = 64) final int eighths) {
    // Treasury coupons are set in eighths of a percent
    final double coupon = eighths * 0.00125;
    final int dated = monthEnd ? Dates.endOfMonth(Dates.of(year, month, 1)) : Dates.of(year, month, 15);
    final int maturity =
        monthEnd ? Dates.endOfMonth(Dates.of(year + years, month, 1)) : Dates.of(year + years, month, 15);
    final FixedRateBond b = new FixedRateBond("p", BondConvention.UST, coupon, dated, maturity);
    assertEquals(2 * years, b.couponCount());
    // 100 * coupon / 2 up to rounding in the year fraction
    assertEquals(50.0 * coupon, b.couponAmount(0), 1e-12);
  }
}
