package io.ratesalgo.backtest.prereg;

import io.ratesalgo.backtest.util.Hashing;
import io.ratesalgo.backtest.util.Yaml;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;
import java.util.function.ToLongFunction;

/**
 * Looks at an evaluation data set, counted across pre-registration ids.
 *
 * <p>Plain idea: the ledger's {@code look} field counts runs of one pre-registration. Ten
 * pre-registrations that each read the same twenty synthetic sessions once are ten looks at
 * those sessions, although every row says look 1. This class gives each row the name of the data
 * it read, so the looks can be counted per data set, and so a new run can be refused until its
 * pre-registration declares the looks already taken.
 *
 * <p>Formally, the key of a row is {@code "sessions:" + h}, where {@code h} is the first 16 hex
 * digits of the SHA-256 of the lines {@code <date>|<seed>\n}, one per distinct (date, seed) pair
 * of the row's {@code journals}, sorted. Rows without journals that carry a {@code data_sha256}
 * get {@code "data:"} plus its first 16 hex digits; any other row has no key. Two runs with the
 * same dates and seeds share a key even when a model change altered the generated bytes: the
 * random draws behind the sessions are the same, which is what makes the results dependent.
 * Rows keyed by a data hash share a key only when they read exactly the same files, so two
 * studies that share one file of several are not grouped; the report lists the file names.
 * {@code ratesresearch.prereg} computes the same keys.
 */
public final class DataSets {

  private DataSets() {}

  /** One data set and the ledger rows that read it, in ledger order. */
  public record Looks(String key, String description, List<Map<String, Object>> rows) {
    public Looks {
      rows = List.copyOf(rows);
    }
  }

  private static String sessionsKey(final Collection<String> lines) {
    final StringBuilder b = new StringBuilder();
    for (final String l : new TreeSet<>(lines)) {
      b.append(l).append('\n');
    }
    return "sessions:" + Hashing.sha256Text(b.toString()).substring(0, 16);
  }

  /** The key of the sessions {@code days} with the seed {@code seedOf} gives each. */
  public static String key(final List<LocalDate> days, final ToLongFunction<LocalDate> seedOf) {
    final List<String> lines = new ArrayList<>();
    for (final LocalDate d : days) {
      lines.add(d + "|" + seedOf.applyAsLong(d));
    }
    return sessionsKey(lines);
  }

  /** The key of a ledger row, or null when the row names no data. */
  public static String key(final Map<String, Object> entry) {
    if (entry.get("journals") instanceof List<?> journals && !journals.isEmpty()) {
      final List<String> lines = new ArrayList<>();
      for (final Object o : journals) {
        final Map<String, Object> j = Yaml.asMap(o, "journal");
        lines.add(j.get("date") + "|" + ((Number) j.get("seed")).longValue());
      }
      return sessionsKey(lines);
    }
    if (entry.get("data_sha256") instanceof String s && s.length() >= 16) {
      return "data:" + s.substring(0, 16);
    }
    return null;
  }

  private static String describe(final Map<String, Object> entry) {
    if (entry.get("journals") instanceof List<?> journals && !journals.isEmpty()) {
      final TreeSet<String> dates = new TreeSet<>();
      final TreeSet<Long> seeds = new TreeSet<>();
      for (final Object o : journals) {
        final Map<String, Object> j = Yaml.asMap(o, "journal");
        dates.add(String.valueOf(j.get("date")));
        seeds.add(((Number) j.get("seed")).longValue());
      }
      return dates.size() + " sessions " + dates.first() + ".." + dates.last() + ", seeds " + seeds.first() + ".."
          + seeds.last();
    }
    final List<String> names = new ArrayList<>();
    if (entry.get("data") instanceof List<?> files) {
      for (final Object f : files) {
        names.add(f instanceof Map<?, ?> m ? String.valueOf(m.get("name")) : String.valueOf(f));
      }
    } else {
      names.add(String.valueOf(entry.get("data")));
    }
    return "files " + String.join(", ", names);
  }

  /** Every data set the ledger names, in order of first use. */
  public static List<Looks> looks(final List<Map<String, Object>> entries) {
    final Map<String, List<Map<String, Object>>> rows = new LinkedHashMap<>();
    for (final Map<String, Object> e : entries) {
      final String k = key(e);
      if (k != null) {
        rows.computeIfAbsent(k, x -> new ArrayList<>()).add(e);
      }
    }
    final List<Looks> out = new ArrayList<>();
    for (final Map.Entry<String, List<Map<String, Object>>> e : rows.entrySet()) {
      out.add(new Looks(e.getKey(), describe(e.getValue().get(0)), e.getValue()));
    }
    return out;
  }

  /** Rows of {@code entries} that read {@code key}. */
  public static long count(final List<Map<String, Object>> entries, final String key) {
    return entries.stream().filter(e -> key.equals(key(e))).count();
  }

  /**
   * Pre-registration ids that have read {@code key} and are neither {@code preregId} itself (its
   * own runs are the {@code look} field) nor in {@code declared}.
   */
  public static List<String> undeclared(
      final List<Map<String, Object>> entries, final String key, final String preregId,
      final Collection<String> declared) {
    final List<String> out = new ArrayList<>();
    for (final Map<String, Object> e : entries) {
      final String id = String.valueOf(e.get("prereg_id"));
      if (key.equals(key(e)) && !id.equals(preregId) && !declared.contains(id) && !out.contains(id)) {
        out.add(id);
      }
    }
    return out;
  }

  /**
   * The problem to refuse a run with, or null when {@code prereg} declares every earlier look at
   * {@code key}. {@code together} are ids run in the same invocation, which need not be declared.
   */
  public static String refusal(
      final List<Map<String, Object>> entries, final String key, final PreRegistration prereg,
      final Collection<String> together) {
    final List<String> declared = new ArrayList<>(prereg.priorLooks());
    declared.addAll(together);
    final List<String> missing = undeclared(entries, key, prereg.id(), declared);
    if (missing.isEmpty()) {
      return null;
    }
    return "data set " + key + " has already been read by " + String.join(", ", missing) + " (" + count(entries, key)
        + " ledger rows); " + prereg.id() + " must declare them: add 'prior_looks: [" + String.join(", ", missing)
        + "]' to the pre-registration and say there how the earlier results are allowed for";
  }

  /** Adds {@code data_set}, {@code data_set_look} and {@code prior_looks} to a record about to be appended. */
  public static void stamp(
      final Map<String, Object> record, final List<Map<String, Object>> entries, final PreRegistration prereg) {
    final String k = key(record);
    if (k != null) {
      record.put("data_set", k);
      record.put("data_set_look", count(entries, k) + 1);
      record.put("prior_looks", prereg.priorLooks());
    }
  }

  /** The looks of every data set as text, with a warning line for each set read more than once. */
  public static String report(final List<Map<String, Object>> entries) {
    final List<Looks> all = looks(entries);
    final StringBuilder b = new StringBuilder(2048);
    int repeated = 0;
    int unkeyed = entries.size();
    for (final Looks l : all) {
      unkeyed -= l.rows().size();
      b.append(l.key()).append("  ").append(l.description()).append(": ").append(l.rows().size())
          .append(l.rows().size() == 1 ? " look\n" : " looks\n");
      int n = 0;
      final List<String> ids = new ArrayList<>();
      for (final Map<String, Object> r : l.rows()) {
        n++;
        ids.add(String.valueOf(r.get("prereg_id")));
        b.append("  look ").append(n).append("  seq ").append(r.get("seq")).append("  ").append(r.get("prereg_id"))
            .append("  ").append(r.get("scope")).append("  ").append(r.get("verdict")).append("  (recorded as look ")
            .append(r.get("look")).append(")\n");
      }
      if (n > 1) {
        repeated++;
        b.append("  warning: ").append(n).append(" looks at the same data by ").append(String.join(", ", ids))
            .append("; treat their verdicts as one family, not as independent results\n");
      }
    }
    b.append(entries.size()).append(" ledger rows, ").append(all.size()).append(" data sets, ").append(repeated)
        .append(" read more than once");
    if (unkeyed > 0) {
      b.append(", ").append(unkeyed).append(" rows name no data");
    }
    return b.append('\n').toString();
  }
}
