from ratesresearch import prereg

ROOT = Path(__file__).resolve().parents[2]
DRAFTS = ["SIM3-BASE-001"] + [f"R5-00{k}" for k in range(1, 8)]

GOOD_CONFIG = (
    "arms: {a: x, b: y}\nseeds: {pilot_base: 29000000, confirmation_base: 33000000,"
    " minimum_sessions: 2000}\n"
    "statistics: {block_sessions: 21, resamples: 2000, bootstrap_seed: 5}\n"
    "smallest_effect: {usd_per_session: 100}\n"
)


def _prereg(data_set: str, extra: str) -> str:
    return (
        "prereg_version: 2\nid: X\ntitle: t\nhypothesis: h\nmetric: m\nbaseline: a\n"
        "treatments: [b]\ntest: t\ndata_set:\n" + data_set + "  simulator_params:"
        " data/calibration/sim_v2_params.json\n  simulator_params_sha256:"
        " 3e2159814ee4e9892ae0dba33f5f35fe0bdd33739df625ea4ae46162c1154fd4\n"
        "success_threshold: s\nassumption_band: {preset: sim_v2_params, parameters: [impact],"
        " points: [low, central, high]}\n"
        "author: a\ndate: 2026-11-23\nconfig: c.yaml\nconfig_sha256: CONFIG_SHA\n" + extra
    )


@pytest.fixture()
def repo(tmp_path: Path) -> Path:
    (tmp_path / "data/calibration").mkdir(parents=True)
    shutil.copy(
        ROOT / "data/calibration/sim_v2_params.json",
        tmp_path / "data/calibration/sim_v2_params.json",
    )
    return tmp_path


def _problems(repo: Path, text: str, config: str) -> list[str]:
    (repo / "c.yaml").write_text(config, encoding="utf-8")
    sha = hashlib.sha256(config.encode("utf-8")).hexdigest()
    (repo / "p.yaml").write_text(text.replace("CONFIG_SHA", sha), encoding="utf-8")
    return prereg.validate(repo / "p.yaml", repo)


@pytest.mark.parametrize("study", DRAFTS)
def test_the_drafts_validate(study: str) -> None:
    assert prereg.validate(ROOT / "research/prereg" / f"{study}.yaml", ROOT) == []


def test_every_rule_names_its_problem(repo: Path) -> None:
    ok = "  seed_base: 33000000\n  sessions: 2000\n"
    assert _problems(repo, _prereg(ok, ""), GOOD_CONFIG) == []
    raw = yaml.safe_load(_prereg(ok, "holdout: [2026-01-02]\n").replace("title: t\n", ""))
    assert prereg.validate_v2(raw, repo) == [
        "missing or blank key 'title'",
        "version 1 date key 'holdout' is not allowed in a session-seed design",
    ]
    # through the loader a dated file is read by the version 1 rules, plus the date-key problem
    dated = _problems(repo, _prereg(ok, "holdout: [2026-01-02]\n"), GOOD_CONFIG)
    assert "missing or blank key 'period'" in dated
    assert "version 1 date key 'holdout' is not allowed in a session-seed design" in dated
    assert _problems(repo, _prereg("  seed_base: 8000000\n  sessions: 50\n", ""), GOOD_CONFIG) == [
        "data_set.seed_base: seed base 8000000 is spent: every session under 8000000 was"
        " generated by the old simulators and read by AUDIT-01 to AUDIT-26 (SIM_V2_DESIGN.md"
        " section 12)",
        "data_set.sessions 50 is below the floor of 2000",
        "config seeds.confirmation_base 33000000 differs from data_set.seed_base 8000000",
    ]
    assert _problems(
        repo, _prereg("  seed_base: 29000000\n  sessions: rule\n", ""), GOOD_CONFIG
    ) == [
        "data_set.seed_base: seed base 29000000 is the pilot base: it sizes a confirmation set"
        " and is then discarded for inference",
        "data_set.sessions must be an integer of at least 2000 once the file is not a draft",
        "config seeds.confirmation_base 33000000 differs from data_set.seed_base 29000000",
    ]
    assert _problems(
        repo, _prereg("  seed_base: 28000000\n  first: 79000\n  sessions: 2000\n", ""), GOOD_CONFIG
    ) == [
        "data_set.seed_base: seed base 28000000 belongs to the simulator's acceptance tests and"
        " supports no claim",
        "data_set.first + sessions exceeds 80000: later sessions' label dates (2030-01-01 plus the"
        " session number in days) overflow epoch nanoseconds",
        "config seeds.confirmation_base 33000000 differs from data_set.seed_base 28000000",
    ]
    draft = _prereg("  seed_base: 33000000\n  sessions: rule\n", "status: draft\n")
    assert _problems(repo, draft, GOOD_CONFIG) == []
    assert _problems(
        repo,
        _prereg(ok, ""),
        "arms: {a: x}\nseeds: {pilot_base: 33000000, minimum_sessions: 100}\n"
        "statistics: {block_sessions: 21, resamples: 0, bootstrap_seed: 5}\n"
        "guards: {speed: 1, hit_rate: 0}\n",
    ) == [
        "config arms do not name the treatment 'b'",
        "config statistics.resamples must be a positive integer",
        "config seeds.pilot_base must be the pilot base 29000000, found 33000000",
        "config seeds.minimum_sessions 100 is below the design's floor of 2000",
        "config guards.speed is not a guard; known: [quoted_share, hit_rate, client_dv01]",
        "config guards.hit_rate must be a positive ratio",
        "config smallest_effect.usd_per_session must be a positive number, stated before the pilot",
    ]
    assert _problems(
        repo,
        _prereg(ok, "prior_looks: none\n")
        .replace("test: t\n", "")
        .replace("treatments: [b]", "treatments: [b, a]")
        .replace("date: 2026-11-23", "date: yesterday")
        .replace(
            "{preset: sim_v2_params, parameters: [impact], points: [low, central, high]}",
            "{preset: x, parameters: [speed], points: [low, middle]}",
        ),
        "other: 1\n",
    ) == [
        "missing or blank key 'test': a comparison names its test",
        "the baseline arm is also listed as a treatment",
        "date is not an ISO date: yesterday",
        "prior_looks must be a list of pre-registration ids",
        "assumption_band.preset must be sim_v2_params, found x",
        "assumption_band.parameters has an unknown parameter 'speed'; known: [winner_half_spread,"
        " all_in_cost, informed_fraction, drift_tau, level_vol, spread_factor, impact, basis,"
        " taker_skill, impact_half_life]",
        "assumption_band.points has an unknown point 'middle'",
        "assumption_band.points must be low, central and high (DR-008)",
        "config must name the arms under 'arms'",
        "config must state the statistics under 'statistics'",
        "config must state the pilot base under 'seeds.pilot_base'",
        "config smallest_effect.usd_per_session must be a positive number, stated before the pilot",
    ]


def test_structural_problems(repo: Path) -> None:
    text = (
        _prereg("  seed_base: x\n  first: -1\n  sessions: 2\n", "")
        .replace("treatments: [b]", "treatments: b")
        .replace("c1154fd4\n", "c1154fd5\n")
        .replace(
            "parameters: [impact], points: [low, central, high]", "parameters: impact, points: low"
        )
        .replace("config: c.yaml", "config: missing.yaml")
    )
    assert _problems(repo, text, GOOD_CONFIG) == [
        "treatments must be a list (empty for a description)",
        "data_set.seed_base must be an integer",
        "data_set.first must be a non-negative integer",
        "data_set.simulator_params_sha256 does not match data/calibration/sim_v2_params.json"
        " (3e2159814ee4e9892ae0dba33f5f35fe0bdd33739df625ea4ae46162c1154fd4)",
        "assumption_band.parameters must be a list of band parameter names",
        "assumption_band.points must be a list",
        "config file not found: missing.yaml",
    ]


def test_not_mappings(repo: Path) -> None:
    text = (
        "prereg_version: 2\nid: X\ntitle: t\nhypothesis: h\nmetric: m\nbaseline: a\n"
        "treatments: []\ndata_set: [1]\nsuccess_threshold: s\nassumption_band: [1]\nauthor: a\n"
        "date: 2026-11-23\nconfig: c.yaml\nconfig_sha256: CONFIG_SHA\n"
    )
    config = GOOD_CONFIG.replace("smallest_effect: {usd_per_session: 100}\n", "")
    assert _problems(repo, text, config) == [
        "data_set must be a mapping with seed_base, sessions and simulator_params",
        "assumption_band must be a mapping",
    ]


def test_session_seed_rows_are_keyed_like_java() -> None:
    assert prereg.sessions_key(30_000_000, 0, 3) == "sessions:98deedb51466d9ff"
    assert prereg.sessions_key(32_000_000, 0, 2000) == "sessions:1099e6645df9e59b"
    row = {
        "prereg_id": "X",
        "seq": 1,
        "session_seeds": {"base": 30_000_000, "first": 0, "count": 3},
    }
    assert prereg.data_set_key(row) == "sessions:98deedb51466d9ff"
    assert "3 simulator v2 sessions, seeds 30000000..30000002: 1 look" in prereg.looks_report([row])
    assert str(prereg.label_date(30_000_005)) == "2030-01-06"


def _row(
    pid: str,
    data_set: str,
    p: float,
    low: float,
    high: float,
    signs: dict[str, int],
    guards_min: dict[str, float],
    quoted: float,
) -> dict[str, object]:
    return {
        "prereg_id": pid,
        "data_set": data_set,
        "guards_min": guards_min,
        "results": {
            "primary": {
                "t": {
                    "paired_p": p,
                    "ci_low": low,
                    "ci_high": high,
                    "guards": {"quoted_share_ratio": quoted},
                }
            },
            "signs_by_band": {"t": signs},
        },
    }


def _ledger(path: Path, rows: list[dict[str, object]]) -> None:
    prev = prereg.GENESIS
    lines = []
    for n, r in enumerate(rows, 1):
        full = dict(r, ledger_version=1, seq=n, prev_sha256=prev)
        line = json.dumps(full, sort_keys=True, separators=(",", ":"))
        lines.append(line)
        prev = prereg.sha256_text(line)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def test_family_report_matches_java(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    plus = {"central": 1, "impact:low": 1}
    rows = [
        _row("A", "sessions:a", 0.001, 10.0, 20.0, plus, {"quoted_share": 0.8}, 0.9),
        _row("B", "sessions:b", 0.004, 10.0, 20.0, plus, {"quoted_share": 0.8}, 0.5),
        _row("C", "sessions:c", 0.010, -20.0, -10.0, {"central": -1}, {}, 1.0),
        _row("D", "sessions:d", 0.300, -5.0, 9.0, {"central": 1, "impact:low": -1}, {}, 1.0),
        _row("E", "sessions:e", 0.020, 1.0, 9.0, plus, {}, 1.0),
        _row("F", "sessions:f", 0.900, -5.0, 9.0, plus, {}, 1.0),
    ]
    ledger = tmp_path / "ledger.jsonl"
    _ledger(ledger, rows)
    family = tmp_path / "family.yaml"
    family.write_text("family: T\nq: 0.05\nmembers: [A, B, C, D, E, F, Z]\n", encoding="utf-8")
    entries = prereg.read_ledger(ledger)
    expected = (
        "family T (q = 0.05): 6 tests from 6 ledger rows\n"
        "  A t_vs_baseline  seq 1  p 0.00100000  bh 0.00600000  ci [10.00, 20.00]  signs +2/-0"
        "  guards ok  verdict supported\n"
        "  B t_vs_baseline  seq 2  p 0.00400000  bh 0.01200000  ci [10.00, 20.00]  signs +2/-0"
        "  guards fail  verdict trading less\n"
        "  C t_vs_baseline  seq 3  p 0.01000000  bh 0.02000000  ci [-20.00, -10.00]  signs +0/-1"
        "  guards unchecked  verdict reversed\n"
        "  D t_vs_baseline  seq 4  p 0.30000000  bh 0.36000000  ci [-5.00, 9.00]  signs +1/-1"
        "  guards unchecked  verdict not robust\n"
        "  E t_vs_baseline  seq 5  p 0.02000000  bh 0.03000000  ci [1.00, 9.00]  signs +2/-0"
        "  guards unchecked  verdict supported if the guards hold\n"
        "  F t_vs_baseline  seq 6  p 0.90000000  bh 0.90000000  ci [-5.00, 9.00]  signs +2/-0"
        "  guards unchecked  verdict inconclusive\n"
    )
    assert prereg.family_report(entries, str(family)) == expected
    assert prereg.family_report(entries, "data_set:sessions:c") == (
        "family data_set:sessions:c (q = 0.05): 1 test from 1 ledger row\n"
        "  C t_vs_baseline  seq 3  p 0.01000000  bh 0.01000000  ci [-20.00, -10.00]  signs +0/-1"
        "  guards unchecked  verdict reversed\n"
    )
    assert prereg.main(["bh", str(ledger), str(family)]) == 0
    assert "verdict supported\n" in capsys.readouterr().out
    assert prereg.main(["bh", str(ledger), str(tmp_path / "none.yaml")]) == 1
    assert prereg.main(["bh", str(ledger)]) == 2
    assert prereg.benjamini_hochberg([0.01, 0.04, 0.03]) == pytest.approx([0.03, 0.04, 0.04])


