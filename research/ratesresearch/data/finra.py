"""FINRA TRACE Treasury transaction data (on-the-run nominal coupons, disseminated since
31 March 2025).

Status: not downloaded. FINRA's API (https://api.finra.org) returned HTTP 401 without an
account token on 2026-10-31, so the data cannot be fetched unattended from this repository.
This module is the loader against a documented file layout, and
``data/fixtures/finra/treasury_trades_fixture.csv`` is a small synthetic file in that layout
(generated by ``write_synthetic_fixture``; it is not FINRA data and is labelled so).

Documented layout (one row per disseminated trade; the column names follow FINRA's Treasury
trade dissemination fields as this loader expects them after export to CSV):

- ``trade_report_time``: ISO-8601 time with offset
- ``cusip``: 9 characters
- ``benchmark``: on-the-run tenor label, one of 2Y, 3Y, 5Y, 7Y, 10Y, 20Y, 30Y
- ``quantity``: par value in USD; capped values carry a trailing ``+``
  (FINRA caps disseminated size; the cap is the number before the ``+``)
- ``price``: clean price per 100
- ``side``: B or S (reporting party's side), may be empty
- ``ats_indicator``: Y or N
"""

from __future__ import annotations

import math
import random
from datetime import UTC, datetime, timedelta
from pathlib import Path

import pandas as pd

COLUMNS = ("trade_report_time", "cusip", "benchmark", "quantity", "price", "side", "ats_indicator")
BENCHMARKS = ("2Y", "3Y", "5Y", "7Y", "10Y", "20Y", "30Y")
STATUS = (
    "not downloaded: FINRA API requires an authenticated account (HTTP 401, 2026-10-31); "
    "loader written against the documented layout, synthetic fixture shipped"
)


def load_treasury_trades(path: str | Path) -> pd.DataFrame:
    """Parse a file in the documented layout into time (UTC), tenor, size_mm, capped, price."""
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    missing = [c for c in COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"{path}: missing columns {missing}")
    qty = df["quantity"].str.replace(",", "", regex=False)
    capped = qty.str.endswith("+")
    size = qty.str.rstrip("+").astype(float) / 1e6
    out = pd.DataFrame(
        {
            "time": pd.to_datetime(df["trade_report_time"], utc=True),
            "benchmark": df["benchmark"],
            "size_mm": size,
            "capped": capped,
            "price": df["price"].astype(float),
        }
    )
    bad = ~out["benchmark"].isin(BENCHMARKS)
    if bad.any():
        raise ValueError(f"{path}: unknown benchmark labels {sorted(set(out.loc[bad, 'benchmark']))}")
    return out


def write_synthetic_fixture(path: str | Path, seed: int = 20261031, n: int = 400) -> None:
    """Write a synthetic file in the documented layout (labelled synthetic in its cusips)."""
    rng = random.Random(seed)
    start = datetime(2025, 10, 1, 11, 0, tzinfo=UTC)  # 07:00 New York (EDT)
    rows = []
    for i in range(n):
        minute = rng.uniform(0, 600)
        if rng.random() < 0.25:
            minute = min(600.0, max(0.0, rng.gauss(90, 8)))  # cluster at 08:30 New York
        t = start + timedelta(minutes=minute)
        bench = rng.choice(BENCHMARKS)
        size = math.exp(rng.gauss(math.log(5.0), 1.1)) * 1e6
        cap = 50e6
        qty = f"{int(cap)}+" if size >= cap else str(int(round(size, -3)))
        rows.append(
            {
                "trade_report_time": t.isoformat(),
                "cusip": f"SYNTH{i:04d}",
                "benchmark": bench,
                "quantity": qty,
                "price": f"{100 + rng.gauss(0, 0.5):.6f}",
                "side": rng.choice(["B", "S", ""]),
                "ats_indicator": rng.choice(["Y", "N"]),
            }
        )
    pd.DataFrame(rows, columns=list(COLUMNS)).to_csv(path, index=False, lineterminator="\n")
